# Report export: every results table can be saved as a PDF (rendered from Markdown/HTML
# with headless Chrome) or as Markdown. Paper size is chosen by the user; orientation is
# chosen automatically from the table widths unless the user fixes it. Each page carries
# an ESCAP / author footer.

ESC_AUTHOR <- "Dr. Md. Nahidul Islam, Gazipur Agricultural University (GAU), Bangladesh"
ESC_PAPERS <- list(A4 = c(8.27, 11.69), Letter = c(8.5, 11), Legal = c(8.5, 14), A3 = c(11.69, 16.54), A5 = c(5.83, 8.27))

esc_strip_html <- function(x) {
  x <- gsub("<sup>(.*?)</sup>", "^\\1", x, perl = TRUE)
  x <- gsub("<[^>]+>", "", x)
  x <- gsub("&chi;", "chi", x, fixed = TRUE); x <- gsub("&dagger;", "+", x, fixed = TRUE)
  x <- gsub("&lt;", "<", x, fixed = TRUE); x <- gsub("&gt;", ">", x, fixed = TRUE)
  gsub("&amp;", "&", x, fixed = TRUE)
}

# Estimate table width (inches) at ~7.5 pt: 0.065 in per character plus cell padding
esc_table_width_in <- function(df) {
  if (is.null(df) || !ncol(df)) return(0)
  w <- vapply(seq_along(df), function(j) {
    v <- c(names(df)[j], as.character(df[[j]])); v <- esc_strip_html(v[!is.na(v)])
    max(nchar(v, type = "width"), 3)
  }, numeric(1))
  sum(pmin(w, 40)) * 0.065 + ncol(df) * 0.12
}

esc_cap_columns <- function(df, max_cols = 18) {
  if (is.null(df) || ncol(df) <= max_cols) return(list(df = df, note = NULL))
  list(df = df[, seq_len(max_cols), drop = FALSE],
       note = sprintf("Only the first %d of %d columns are shown; download the CSV for the full table.", max_cols, ncol(df)))
}

esc_report_layout <- function(tables, paper = "A4", orientation = "auto") {
  sz <- ESC_PAPERS[[paper]] %||% ESC_PAPERS$A4
  widest <- max(c(0, vapply(tables, esc_table_width_in, numeric(1))))
  land <- switch(orientation, landscape = TRUE, portrait = FALSE, widest > (sz[1] - 1.2))
  list(width = if (land) sz[2] else sz[1], height = if (land) sz[1] else sz[2], landscape = land)
}

esc_df_to_html <- function(df, html = TRUE) {
  if (is.null(df) || !nrow(df)) return("<p><i>No rows.</i></p>")
  df <- as.data.frame(df, check.names = FALSE, stringsAsFactors = FALSE)
  for (j in seq_along(df)) if (is.numeric(df[[j]])) df[[j]] <- format(signif(df[[j]], 5), trim = TRUE, drop0trailing = TRUE)
  esc <- function(x) if (html) x else htmltools::htmlEscape(x)
  rn <- rownames(df); show_rn <- !is.null(rn) && !identical(rn, as.character(seq_len(nrow(df))))
  head <- paste0("<tr>", if (show_rn) "<th></th>", paste0("<th>", esc(names(df)), "</th>", collapse = ""), "</tr>")
  body <- vapply(seq_len(nrow(df)), function(i) {
    cells <- vapply(df[i, , drop = TRUE], function(v) if (is.na(v)) "" else esc(as.character(v)), "")
    paste0("<tr>", if (show_rn) paste0("<td><b>", esc(rn[i]), "</b></td>"), paste0("<td>", cells, "</td>", collapse = ""), "</tr>")
  }, "")
  paste0("<table>", head, paste(body, collapse = ""), "</table>")
}

esc_report_html <- function(title, sections, settings = NULL, landscape = FALSE) {
  css <- "body{font-family:'Times New Roman',Times,serif;font-size:10pt;color:#111;margin:0}
  h1{font-size:15pt;margin:0 0 4px 0;color:#003366} h2{font-size:12pt;margin:14px 0 4px 0;color:#003366;page-break-after:avoid}
  .meta{font-size:8.5pt;color:#444;margin-bottom:8px}
  table{border-collapse:collapse;margin:4px 0 6px 0;font-size:8pt;page-break-inside:auto}
  tr{page-break-inside:avoid} th{border-top:1.2px solid #000;border-bottom:0.8px solid #000;padding:2px 5px;text-align:left;background:#f2f5f9}
  td{padding:1.5px 5px;border-bottom:0.3px solid #ddd;vertical-align:top} table tr:last-child td{border-bottom:1.2px solid #000}
  .note{font-size:7.5pt;color:#333;margin:2px 0 8px 0} .end{margin-top:18px;font-size:8pt;color:#555;border-top:0.5px solid #999;padding-top:4px}"
  secs <- vapply(sections, function(s) paste0(
    if (!is.null(s$heading)) paste0("<h2>", s$heading, "</h2>") else "",
    if (!is.null(s$text)) paste0("<p>", s$text, "</p>") else "",
    if (!is.null(s$table)) esc_df_to_html(s$table, html = !isFALSE(s$html)) else "",
    if (!is.null(s$note)) paste0("<div class='note'>", s$note, "</div>") else ""), "")
  set <- if (length(settings)) paste0("<div class='meta'>", paste0("<b>", names(settings), ":</b> ", settings, collapse = " &nbsp;|&nbsp; "), "</div>") else ""
  paste0("<!DOCTYPE html><html><head><meta charset='utf-8'><title>", htmltools::htmlEscape(title), "</title><style>", css,
         "</style></head><body><h1>", htmltools::htmlEscape(title), "</h1><div class='meta'>Generated ",
         format(Sys.time(), "%d %B %Y, %H:%M"), " with ESCAP (Easy Statistics, Chemometrics and Plotting).</div>",
         set, paste(secs, collapse = ""),
         "<div class='end'>Report generated by <b>ESCAP</b>: Easy Statistics, Chemometrics and Plotting (analysis.gau.edu.bd). ",
         "Developer: ", ESC_AUTHOR, ". Please cite ESCAP when you use these results.</div></body></html>")
}

esc_report_pdf <- function(file, title, sections, paper = "A4", orientation = "auto", settings = NULL) {
  tabs <- lapply(sections, `[[`, "table")
  lay <- esc_report_layout(Filter(Negate(is.null), tabs), paper, orientation)
  html <- esc_report_html(title, sections, settings, lay$landscape)
  tmp <- tempfile(fileext = ".html"); writeLines(html, tmp, useBytes = TRUE)
  footer <- paste0("<div style='font-size:7px;width:100%;padding:0 12mm;color:#555;font-family:Arial;display:flex;justify-content:space-between'>",
                   "<span>ESCAP: Easy Statistics, Chemometrics and Plotting | ", htmltools::htmlEscape(ESC_AUTHOR), "</span>",
                   "<span>Page <span class='pageNumber'></span> of <span class='totalPages'></span></span></div>")
  ok <- tryCatch({
    pagedown::chrome_print(tmp, output = file, verbose = 0, timeout = 60, options = list(
      paperWidth = lay$width, paperHeight = lay$height, landscape = FALSE,
      displayHeaderFooter = TRUE, headerTemplate = "<div></div>", footerTemplate = footer,
      marginTop = 0.5, marginBottom = 0.6, marginLeft = 0.5, marginRight = 0.5, printBackground = TRUE))
    file.exists(file)
  }, error = function(e) { message("chrome_print failed: ", conditionMessage(e)); FALSE })
  if (!isTRUE(ok)) esc_report_pdf_grid(file, title, sections, lay)
  invisible(file)
}

# Fallback without Chrome: tables drawn with grid (gridExtra), same footer
esc_report_pdf_grid <- function(file, title, sections, lay) {
  grDevices::cairo_pdf(file, width = lay$width, height = lay$height, onefile = TRUE)
  on.exit(grDevices::dev.off())
  page <- 0
  foot <- function() {
    page <<- page + 1
    grid::grid.text(paste0("ESCAP: Easy Statistics, Chemometrics and Plotting | ", ESC_AUTHOR, " | page ", page),
                    x = 0.5, y = grid::unit(0.3, "in"), gp = grid::gpar(fontsize = 6.5, col = "grey35"))
  }
  grid::grid.newpage(); grid::grid.text(title, y = 0.95, gp = grid::gpar(fontsize = 14, fontface = "bold")); foot()
  for (s in sections) {
    if (is.null(s$table)) next
    df <- as.data.frame(lapply(s$table, function(x) esc_strip_html(as.character(x))), check.names = FALSE)
    per <- max(5, floor((lay$height - 1.6) / 0.19))
    for (k in split(seq_len(nrow(df)), ceiling(seq_len(nrow(df)) / per))) {
      grid::grid.newpage()
      grid::grid.text(s$heading %||% "", x = 0.05, y = grid::unit(lay$height - 0.4, "in"), just = "left",
                      gp = grid::gpar(fontsize = 11, fontface = "bold"))
      g <- gridExtra::tableGrob(df[k, , drop = FALSE], rows = NULL, theme = gridExtra::ttheme_minimal(base_size = 7))
      grid::grid.draw(g); foot()
    }
  }
}

esc_report_md <- function(file, title, sections, settings = NULL) {
  lines <- c(paste("#", title), "", paste0("*Generated ", format(Sys.time(), "%d %B %Y, %H:%M"), " with ESCAP.*"), "")
  if (length(settings)) lines <- c(lines, paste0("**", names(settings), ":** ", settings, "  "), "")
  for (s in sections) {
    if (!is.null(s$heading)) lines <- c(lines, paste("##", s$heading), "")
    if (!is.null(s$text)) lines <- c(lines, esc_strip_html(s$text), "")
    if (!is.null(s$table)) {
      df <- as.data.frame(lapply(s$table, function(x) esc_strip_html(as.character(x))), check.names = FALSE)
      lines <- c(lines, knitr::kable(df, format = "pipe"), "")
    }
    if (!is.null(s$note)) lines <- c(lines, paste0("*", esc_strip_html(s$note), "*"), "")
  }
  lines <- c(lines, "---", paste0("Report generated by **ESCAP**: Easy Statistics, Chemometrics and Plotting. Developer: ", ESC_AUTHOR, "."))
  writeLines(lines, file, useBytes = TRUE)
}

# ---------------------------------------------------------------------------
# Word (.docx) report written directly as Office Open XML: no extra packages needed apart from
# a zip routine (the 'zip' package if installed, otherwise utils::zip). Same content, page size,
# automatic orientation and ESCAP / author footer as the PDF; letters stay superscript.
# ---------------------------------------------------------------------------
esc_xml <- function(x) { x <- gsub("&", "&amp;", x, fixed = TRUE); x <- gsub("<", "&lt;", x, fixed = TRUE); gsub(">", "&gt;", x, fixed = TRUE) }

# HTML-ish cell text -> Word runs (keeps <sup>, <sub>, <b>, <i>; strips other tags)
esc_docx_runs <- function(x, size = 18, bold = FALSE, italic = FALSE) {
  x <- as.character(x); if (is.na(x)) x <- ""
  x <- gsub("&plusmn;", "\u00b1", x, fixed = TRUE); x <- gsub("&dagger;", "\u2020", x, fixed = TRUE)
  x <- gsub("&chi;", "\u03c7", x, fixed = TRUE); x <- gsub("&nbsp;", " ", x, fixed = TRUE)
  x <- gsub("<br\\s*/?>", " ", x, perl = TRUE)
  x <- gsub("<(?!/?(sup|sub|b|i|br)\\b)", "&lt;", x, perl = TRUE)   # a literal "<" (e.g. "<1 y", "<0.001") is text, not a tag
  parts <- regmatches(x, gregexpr("<(sup|sub|b|i)>.*?</\\1>|[^<]+|<[^>]+>", x, perl = TRUE))[[1]]
  run <- function(t, extra = "") {
    t <- gsub("&lt;", "<", t, fixed = TRUE); t <- gsub("&gt;", ">", t, fixed = TRUE); t <- gsub("&amp;", "&", t, fixed = TRUE)
    t <- gsub("&#39;", "'", t, fixed = TRUE); t <- gsub("&quot;", "\"", t, fixed = TRUE)
    paste0("<w:r><w:rPr><w:rFonts w:ascii=\"Times New Roman\" w:hAnsi=\"Times New Roman\" w:cs=\"Times New Roman\"/>",
           if (bold) "<w:b/>", if (italic) "<w:i/>", extra, "<w:sz w:val=\"", size, "\"/></w:rPr><w:t xml:space=\"preserve\">",
           esc_xml(t), "</w:t></w:r>")
  }
  paste(vapply(parts, function(p) {
    if (grepl("^<sup>", p)) run(gsub("</?sup>", "", p), "<w:vertAlign w:val=\"superscript\"/>")
    else if (grepl("^<sub>", p)) run(gsub("</?sub>", "", p), "<w:vertAlign w:val=\"subscript\"/>")
    else if (grepl("^<b>", p)) run(gsub("</?b>", "", p), "<w:b/>")
    else if (grepl("^<i>", p)) run(gsub("</?i>", "", p), "<w:i/>")
    else if (grepl("^<", p)) ""
    else run(p)
  }, ""), collapse = "")
}

esc_docx_par <- function(runs, after = 80, keep_next = FALSE)
  paste0("<w:p><w:pPr>", if (keep_next) "<w:keepNext/>", "<w:spacing w:before=\"0\" w:after=\"", after, "\"/></w:pPr>", runs, "</w:p>")

esc_docx_table <- function(df, html = TRUE) {
  df <- as.data.frame(df, check.names = FALSE, stringsAsFactors = FALSE)
  for (j in seq_along(df)) if (is.numeric(df[[j]])) df[[j]] <- format(signif(df[[j]], 5), trim = TRUE, drop0trailing = TRUE)
  rn <- rownames(df); if (!is.null(rn) && !identical(rn, as.character(seq_len(nrow(df))))) df <- cbind(` ` = rn, df)
  prep <- function(v) { v <- ifelse(is.na(v), "", as.character(v)); if (html) v else esc_xml(v) }
  cell <- function(txt, head = FALSE, last = FALSE) {
    b <- if (head) "<w:tcBorders><w:top w:val=\"single\" w:sz=\"12\" w:color=\"000000\"/><w:bottom w:val=\"single\" w:sz=\"6\" w:color=\"000000\"/></w:tcBorders>"
         else if (last) "<w:tcBorders><w:bottom w:val=\"single\" w:sz=\"12\" w:color=\"000000\"/></w:tcBorders>" else ""
    paste0("<w:tc><w:tcPr>", b, "<w:tcMar><w:left w:w=\"70\" w:type=\"dxa\"/><w:right w:w=\"70\" w:type=\"dxa\"/></w:tcMar></w:tcPr>",
           "<w:p><w:pPr><w:spacing w:before=\"0\" w:after=\"0\"/></w:pPr>", esc_docx_runs(txt, 18, bold = head), "</w:p></w:tc>")
  }
  hdr <- paste0("<w:tr><w:trPr><w:tblHeader/></w:trPr>", paste(vapply(names(df), function(h)
    cell(if (html) gsub("</?i>", "", h) else esc_xml(h), TRUE), ""), collapse = ""), "</w:tr>")
  body <- vapply(seq_len(nrow(df)), function(i) paste0("<w:tr><w:trPr><w:cantSplit/></w:trPr>",
    paste(vapply(df[i, , drop = TRUE], function(v) cell(prep(v), FALSE, i == nrow(df)), ""), collapse = ""), "</w:tr>"), "")
  paste0("<w:tbl><w:tblPr><w:tblW w:w=\"0\" w:type=\"auto\"/><w:tblLayout w:type=\"autofit\"/></w:tblPr>", hdr, paste(body, collapse = ""), "</w:tbl>",
         esc_docx_par("", 60))
}

esc_report_docx <- function(file, title, sections, paper = "A4", orientation = "auto", settings = NULL) {
  tabs <- Filter(Negate(is.null), lapply(sections, `[[`, "table"))
  lay <- esc_report_layout(tabs, paper, orientation)
  body <- c(esc_docx_par(esc_docx_runs(title, 30, bold = TRUE), 60),
            esc_docx_par(esc_docx_runs(paste0("Generated ", format(Sys.time(), "%d %B %Y, %H:%M"),
                                              " with ESCAP (Easy Statistics, Chemometrics and Plotting)."), 17, italic = TRUE), 60))
  if (length(settings)) body <- c(body, esc_docx_par(paste0(vapply(seq_along(settings), function(i)
    paste0(esc_docx_runs(paste0(names(settings)[i], ": "), 17, bold = TRUE), esc_docx_runs(esc_xml(settings[[i]]), 17),
           if (i < length(settings)) esc_docx_runs("   |   ", 17) else ""), ""), collapse = ""), 120))
  for (s in sections) {
    if (!is.null(s$heading)) body <- c(body, esc_docx_par(esc_docx_runs(s$heading, 24, bold = TRUE), 60, keep_next = TRUE))
    if (!is.null(s$text)) body <- c(body, esc_docx_par(esc_docx_runs(s$text, 20)))
    if (!is.null(s$table)) body <- c(body, esc_docx_table(s$table, html = !isFALSE(s$html)))
    if (!is.null(s$note)) body <- c(body, esc_docx_par(esc_docx_runs(s$note, 16, italic = TRUE), 160))
  }
  body <- c(body, esc_docx_par(esc_docx_runs(paste0("Report generated by ESCAP: Easy Statistics, Chemometrics and Plotting (analysis.gau.edu.bd). Developer: ",
                                                    ESC_AUTHOR, ". Please cite ESCAP when you use these results."), 16, italic = TRUE)))
  tw <- function(inch) round(inch * 1440)
  sect <- paste0("<w:sectPr><w:footerReference w:type=\"default\" r:id=\"rIdFooter1\"/>",
                 "<w:pgSz w:w=\"", tw(lay$width), "\" w:h=\"", tw(lay$height), "\"", if (lay$landscape) " w:orient=\"landscape\"", "/>",
                 "<w:pgMar w:top=\"720\" w:right=\"720\" w:bottom=\"864\" w:left=\"720\" w:header=\"360\" w:footer=\"360\" w:gutter=\"0\"/></w:sectPr>")
  ns <- "xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\" xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\""
  doc <- paste0("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><w:document ", ns, "><w:body>",
                paste(body, collapse = ""), sect, "</w:body></w:document>")
  fld <- function(code) paste0("<w:r><w:rPr><w:sz w:val=\"14\"/></w:rPr><w:fldChar w:fldCharType=\"begin\"/></w:r><w:r><w:rPr><w:sz w:val=\"14\"/></w:rPr><w:instrText xml:space=\"preserve\"> ",
                               code, " </w:instrText></w:r><w:r><w:rPr><w:sz w:val=\"14\"/></w:rPr><w:fldChar w:fldCharType=\"end\"/></w:r>")
  foot <- paste0("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><w:ftr ", ns, "><w:p><w:pPr><w:tabs><w:tab w:val=\"right\" w:pos=\"",
                 tw(lay$width - 1), "\"/></w:tabs></w:pPr>", esc_docx_runs(paste0("ESCAP: Easy Statistics, Chemometrics and Plotting | ", ESC_AUTHOR), 14),
                 "<w:r><w:tab/></w:r>", esc_docx_runs("Page ", 14), fld("PAGE"), esc_docx_runs(" of ", 14), fld("NUMPAGES"), "</w:p></w:ftr>")
  ct <- paste0("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">",
               "<Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>",
               "<Default Extension=\"xml\" ContentType=\"application/xml\"/>",
               "<Override PartName=\"/word/document.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml\"/>",
               "<Override PartName=\"/word/footer1.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml\"/></Types>")
  rels <- paste0("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">",
                 "<Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"word/document.xml\"/></Relationships>")
  drels <- paste0("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">",
                  "<Relationship Id=\"rIdFooter1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/footer\" Target=\"footer1.xml\"/></Relationships>")
  dir <- tempfile("escap_docx_"); dir.create(file.path(dir, "_rels"), recursive = TRUE); dir.create(file.path(dir, "word", "_rels"), recursive = TRUE)
  w <- function(txt, path) { con <- file(file.path(dir, path), open = "wb"); writeBin(charToRaw(enc2utf8(txt)), con); close(con) }
  w(ct, "[Content_Types].xml"); w(rels, "_rels/.rels"); w(doc, "word/document.xml"); w(drels, "word/_rels/document.xml.rels"); w(foot, "word/footer1.xml")
  parts <- c("[Content_Types].xml", "_rels/.rels", "word/document.xml", "word/_rels/document.xml.rels", "word/footer1.xml")
  out <- normalizePath(file, mustWork = FALSE); if (file.exists(out)) file.remove(out)
  if (requireNamespace("zip", quietly = TRUE)) zip::zip(out, files = parts, root = dir, mode = "mirror")
  else { old <- setwd(dir); on.exit(setwd(old), add = TRUE); utils::zip(out, parts, flags = "-r9Xq") }
  unlink(dir, recursive = TRUE)
  invisible(file)
}
